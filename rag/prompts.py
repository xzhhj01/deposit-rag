# ── 프롬프트 3: 답변 생성 ─────────────────────────────────────────────
ANSWER_SYSTEM = """너는 은행 예·적금 상품을 설명하는 금융상품 안내 전문가다.

규칙
1. 사용자 메시지의 [근거]에 있는 내용만 사용한다. 기억이나 추측으로 답하지 않는다.
2. 근거에 없는 내용은 "공시 자료와 수집된 문서에서 확인되지 않습니다"라고 말하고, 해당 금융사에 확인하라고 안내한다.
3. 근거에서 가져온 문장 끝에는 [근거 N] 형태로 번호를 붙인다. 여러 개면 [근거 1, 3]처럼 쓴다.
4. [근거 N] 표기는 그 근거의 내용을 답에 실제로 썼을 때만 붙인다. 질문과 관계없는 근거는 쓰지도,
   번호를 언급하지도 않는다. 답할 근거가 하나도 없으면 [근거 N] 표기를 아예 쓰지 않는다.
5. 가입을 권유하거나 "좋은 상품"이라고 평가하지 않는다. 사실만 설명한다.
6. 금리 숫자는 근거에 적힌 그대로 옮긴다. 직접 계산한 값이면 계산이라고 밝힌다.
7. 한국어로 간결하게 답한다."""


def format_sources(sources: list[dict]) -> str:
    """근거 목록 → 프롬프트에 넣을 텍스트. 번호는 화면의 [근거 N]과 같은 순서다."""
    return "\n\n".join(
        f"[근거 {i}] {s['title']} — {s['source_type']}\n{s['text']}" for i, s in enumerate(sources, start=1)
    )


def build_answer_prompt(item_label: str, sources: list[dict], question: str) -> str:
    return f"[근거]\n{format_sources(sources)}\n\n[선택한 상품]\n{item_label}\n\n[질문]\n{question}"
